/* A small C++ convenience layer over rci.h.
 *
 * The C ABI is already usable from C; this header exists because the three
 * things a C++ caller gets wrong are mechanical — forgetting rci_string_free,
 * holding the handle past a throw, and turning {"error": ...} into a return
 * value. They are handled once:
 *
 *     #include "rci.hpp"
 *     int main() {
 *         rci::Library lib;                        // throws rci::Error
 *         auto client = lib.client("chrome150");
 *         auto reply = client.get("https://tls.peet.ws/api/all");
 *         std::printf("%ld %s\n", reply.status, reply.version.c_str());
 *     }
 *
 * Header-only C++17, no JSON dependency: it reads the handful of flat keys a
 * caller needs and hands the raw JSON back for everything nested. The
 * pointer-owning types are move-only; copying one would free the same
 * library allocation twice.
 *
 * Building: g++ -std=c++17 -I include main.cpp -L lib -lrust_curl_impersonate_ffi
 * (BoringSSL is C++, so the C++ driver is required anyway).
 */
#ifndef RCI_HPP
#define RCI_HPP

#include <cstdint>
#include <stdexcept>
#include <string>
#include <utility>
#include <vector>

#include "rci.h"

namespace rci {

/** A failure reported by the library: a NULL handle or an {"error": ...} reply. */
class Error : public std::runtime_error {
public:
    explicit Error(const std::string& message) : std::runtime_error(message) {}
};

namespace detail {

/**
 * The string value of a top-level key in one of the ABI's flat objects:
 * `{"status":200,"version":"HTTP/1.1",...}`.
 *
 * This is not a JSON parser. The ABI's own replies are generated by
 * serde_json from a fixed shape, so a scan for `"key":` followed by a quoted
 * string is exact for the keys this header reads. A caller that needs the
 * nested arrays (headers, activity) should parse `Reply::json` with the JSON
 * library the project already uses, which is what the C ABI's text form is for.
 */
std::string flatField(const std::string& json, const std::string& key);
/** The same scan for a numeric field. Returns false when the key is absent. */
bool flatNumber(const std::string& json, const std::string& key, long& value);
/**
 * The same scan for a bare (unquoted) value: `true`, `false`, `null` or a
 * number. Returns false when the key is absent, and the raw token otherwise.
 */
bool flatToken(const std::string& json, const std::string& key, std::string& token);
/** True when the object carries a non-empty "error" string. */
bool hasError(const std::string& json);

}  // namespace detail

/** Decodes an escape sequence in a JSON string body. */
std::string unescape(const std::string& quoted);

/** One owned `char *` from the library, released exactly once. */
class Owned {
public:
    Owned() = default;
    explicit Owned(char* text) : text_(text) {}
    Owned(const Owned&) = delete;
    Owned& operator=(const Owned&) = delete;
    Owned(Owned&& other) noexcept : text_(other.text_) { other.text_ = nullptr; }
    Owned& operator=(Owned&& other) noexcept {
        if (this != &other) {
            reset();
            text_ = other.text_;
            other.text_ = nullptr;
        }
        return *this;
    }
    ~Owned() { reset(); }

    std::string str() const { return text_ == nullptr ? std::string() : std::string(text_); }

    /** Releases the string and returns it, for callers that want a std::string. */
    std::string take() {
        std::string value = str();
        reset();
        return value;
    }

private:
    void reset() {
        if (text_ != nullptr) {
            rci_string_free(text_);
            text_ = nullptr;
        }
    }
    char* text_ = nullptr;
};

/** One response. */
struct Reply {
    long status = 0;
    std::string version;
    std::string url;
    std::string body;
    bool body_is_text = true;
    /** The raw JSON: the header list and everything this struct omits. */
    std::string json;
};

/** One handle. Move-only. */
class Client {
public:
    Client() = default;
    explicit Client(RciClient* handle) : handle_(handle) {}
    Client(const Client&) = delete;
    Client& operator=(const Client&) = delete;
    Client(Client&& other) noexcept : handle_(other.handle_) { other.handle_ = nullptr; }
    Client& operator=(Client&& other) noexcept {
        if (this != &other) {
            reset();
            handle_ = other.handle_;
            other.handle_ = nullptr;
        }
        return *this;
    }
    ~Client() { reset(); }

    bool valid() const { return handle_ != nullptr; }
    RciClient* raw() const { return handle_; }

    /** Send a request; throws rci::Error on an {"error": ...} reply. */
    Reply request(const std::string& method, const std::string& url);
    Reply requestWithHeaders(
        const std::string& method,
        const std::string& url,
        const std::string& headers_json,
        const std::string& body);
    Reply get(const std::string& url) { return request("GET", url); }

    /** The raw JSON of the handle's introspection functions. */
    std::string lastHeaders() const;
    std::string activity() const;
    std::string wireProfile() const;

private:
    void reset() {
        if (handle_ != nullptr) {
            rci_client_free(handle_);
            handle_ = nullptr;
        }
    }
    RciClient* handle_ = nullptr;
};

/** The library: version, profile queries, client construction, registration. */
class Library {
public:
    /** Throws when the ABI is older than 2. */
    Library() {
        if (rci_version() < 2) {
            throw Error("library reports an ABI older than 2");
        }
    }

    uint32_t version() const { return rci_version(); }
    std::string targets() const { return Owned(rci_targets()).take(); }
    std::string profiles() const { return Owned(rci_profiles()).take(); }

    /** The profile's metadata JSON; throws on an unknown name. */
    std::string profileInfo(const std::string& name) const {
        std::string text = Owned(rci_profile_info(name.c_str())).take();
        if (detail::hasError(text)) throw Error(detail::flatField(text, "error"));
        return text;
    }

    /** Create a handle; throws Error with rci_last_error on a NULL return. */
    Client client(const std::string& profile) {
        return wrap(rci_client_new(profile.c_str()), "rci_client_new");
    }

    Client client(const std::string& profile, const std::string& options_json) {
        return wrap(
            rci_client_new_with_options(profile.c_str(), options_json.c_str()),
            "rci_client_new_with_options");
    }

    /** One-shot GET; it keeps no cookie or connection between calls. */
    Reply get(const std::string& profile, const std::string& url) {
        return decode(Owned(rci_get(profile.c_str(), url.c_str())).take());
    }

    /** Registers a library-schema JSON document for this process. */
    void loadFingerprints(const std::string& document) {
        std::string text = Owned(rci_load_fingerprints(document.c_str())).take();
        if (detail::hasError(text)) throw Error(detail::flatField(text, "error"));
    }

    /** Turns the ABI's reply text into a Reply, throwing on {"error": ...}. */
    static Reply decode(const std::string& text);

private:
    Client wrap(RciClient* handle, const char* function) {
        if (handle == nullptr) {
            const char* message = rci_last_error();
            throw Error(message != nullptr && *message != '\0' ? message
                                                                  : std::string(function) + " returned NULL");
        }
        return Client(handle);
    }
};

// -- inline definitions ----------------------------------------------------

inline std::string unescape(const std::string& quoted) {
    std::string out;
    out.reserve(quoted.size());
    for (std::size_t index = 0; index < quoted.size(); ++index) {
        char value = quoted[index];
        if (value != '\\' || index + 1 >= quoted.size()) {
            out.push_back(value);
            continue;
        }
        char next = quoted[++index];
        switch (next) {
            case 'n': out.push_back('\n'); break;
            case 't': out.push_back('\t'); break;
            case 'r': out.push_back('\r'); break;
            case 'b': out.push_back('\b'); break;
            case 'f': out.push_back('\f'); break;
            case '"': out.push_back('"'); break;
            case '\\': out.push_back('\\'); break;
            case '/': out.push_back('/'); break;
            case 'u': {
                // \uXXXX: only the BMP is decoded; a surrogate pair would need
                // the next escape, and the ABI does not emit one for the
                // fields this header reads.
                if (index + 4 >= quoted.size()) {
                    out.push_back('u');
                    break;
                }
                unsigned code = 0;
                for (int digit = 0; digit < 4; ++digit) {
                    char hex = quoted[index + 1 + digit];
                    code <<= 4;
                    if (hex >= '0' && hex <= '9') code |= static_cast<unsigned>(hex - '0');
                    else if (hex >= 'a' && hex <= 'f') code |= static_cast<unsigned>(hex - 'a' + 10);
                    else if (hex >= 'A' && hex <= 'F') code |= static_cast<unsigned>(hex - 'A' + 10);
                }
                index += 4;
                // UTF-8 encode without pulling in <codecvt>.
                if (code < 0x80) {
                    out.push_back(static_cast<char>(code));
                } else if (code < 0x800) {
                    out.push_back(static_cast<char>(0xC0 | (code >> 6)));
                    out.push_back(static_cast<char>(0x80 | (code & 0x3F)));
                } else {
                    out.push_back(static_cast<char>(0xE0 | (code >> 12)));
                    out.push_back(static_cast<char>(0x80 | ((code >> 6) & 0x3F)));
                    out.push_back(static_cast<char>(0x80 | (code & 0x3F)));
                }
                break;
            }
            default: out.push_back(next); break;
        }
    }
    return out;
}

namespace detail {

inline std::size_t findKey(const std::string& json, const std::string& key) {
    const std::string needle = "\"" + key + "\":";
    std::size_t at = json.find(needle);
    if (at == std::string::npos) return std::string::npos;
    return at + needle.size();
}

inline std::string flatField(const std::string& json, const std::string& key) {
    std::size_t start = findKey(json, key);
    if (start == std::string::npos || start >= json.size() || json[start] != '"') return std::string();
    std::size_t end = start + 1;
    std::string body;
    while (end < json.size()) {
        char value = json[end];
        if (value == '\\' && end + 1 < json.size()) {
            body.push_back(value);
            body.push_back(json[end + 1]);
            end += 2;
            continue;
        }
        if (value == '"') break;
        body.push_back(value);
        ++end;
    }
    return unescape(body);
}

inline bool flatNumber(const std::string& json, const std::string& key, long& value) {
    std::size_t start = findKey(json, key);
    if (start == std::string::npos || start >= json.size()) return false;
    std::size_t end = start;
    while (end < json.size() && (json[end] == '-' || (json[end] >= '0' && json[end] <= '9'))) ++end;
    if (end == start) return false;
    value = std::stol(json.substr(start, end - start));
    return true;
}

inline bool flatToken(const std::string& json, const std::string& key, std::string& token) {
    std::size_t start = findKey(json, key);
    if (start == std::string::npos) return false;
    while (start < json.size() && json[start] == ' ') ++start;
    std::size_t end = start;
    while (end < json.size()) {
        char value = json[end];
        if (value == ',' || value == '}' || value == ' ' || value == '\n') break;
        ++end;
    }
    if (end == start) return false;
    token = json.substr(start, end - start);
    return true;
}

inline bool hasError(const std::string& json) {
    return !flatField(json, "error").empty();
}

}  // namespace detail

inline Reply Library::decode(const std::string& text) {
    if (detail::hasError(text)) throw Error(detail::flatField(text, "error"));
    Reply reply;
    reply.json = text;
    detail::flatNumber(text, "status", reply.status);
    reply.version = detail::flatField(text, "version");
    reply.url = detail::flatField(text, "url");
    reply.body = detail::flatField(text, "body");
    // body_is_text is a bare boolean, not a quoted string: serde_json writes
    // `"body_is_text":false`. Reading it as a string field found nothing and
    // left every binary body marked as text.
    std::string token;
    reply.body_is_text = !detail::flatToken(text, "body_is_text", token) || token != "false";
    return reply;
}

inline Reply Client::request(const std::string& method, const std::string& url) {
    if (handle_ == nullptr) throw Error("rci: client is closed");
    std::string text = Owned(rci_request(handle_, method.c_str(), url.c_str(), nullptr, 0)).take();
    return Library::decode(text);
}

inline Reply Client::requestWithHeaders(
    const std::string& method,
    const std::string& url,
    const std::string& headers_json,
    const std::string& body) {
    if (handle_ == nullptr) throw Error("rci: client is closed");
    std::string text = Owned(rci_request_with(
                                 handle_,
                                 method.c_str(),
                                 url.c_str(),
                                 headers_json.empty() ? nullptr : headers_json.c_str(),
                                 body.empty() ? nullptr : body.c_str()))
                           .take();
    return Library::decode(text);
}

inline std::string Client::lastHeaders() const {
    if (handle_ == nullptr) throw Error("rci: client is closed");
    return Owned(rci_client_last_headers(handle_)).take();
}

inline std::string Client::activity() const {
    if (handle_ == nullptr) throw Error("rci: client is closed");
    return Owned(rci_client_activity(handle_)).take();
}

inline std::string Client::wireProfile() const {
    if (handle_ == nullptr) throw Error("rci: client is closed");
    return Owned(rci_client_profile(handle_)).take();
}

}  // namespace rci

#endif  // RCI_HPP
