//! Loadable sources of fingerprint records.
//!
//! The library is not a fixed blob compiled into the crate: every record comes
//! from a [`FingerprintProvider`]. [`BuiltinProvider`] is the library embedded
//! in this crate. [`JsonProvider`], [`DirProvider`], [`FnProvider`] and
//! [`RemoteProvider`] let a caller supply its own records — from a JSON
//! document, from a directory of documents, from anything a closure can fetch,
//! or from a URL that serves the library schema. That last one is the seam a
//! cloud fingerprint service plugs into. [`Profile::find`] then resolves names
//! across every registered provider.
//!
//! ```no_run
//! use rust_curl_impersonate::fingerprint::provider::{JsonProvider, register_provider};
//!
//! let json = r#"{"name":"my_client","tls":{"ciphers":"TLS_AES_128_GCM_SHA256"}}"#;
//! register_provider(JsonProvider::new("acme", json)).unwrap();
//! let profile = rust_curl_impersonate::Profile::find("my_client").unwrap();
//! ```
//!
//! # Precedence
//!
//! Every provider carries a priority. When two providers supply a record with
//! the same name, the higher priority wins; a tie goes to the provider
//! registered later. The embedded library sits at [`PRIORITY_BUILTIN`], below
//! [`PRIORITY_CLOUD`] and [`PRIORITY_USER`], so an application can patch an
//! embedded record without waiting for a crate release. [`providers`] reports
//! which names a provider shadows.
//!
//! # Lifetime
//!
//! A provider is loaded once, when it is registered, and its records are kept
//! for the rest of the process. [`refresh_providers`] reloads them. `load` runs
//! **without** the registry lock, so a slow provider (a network fetch, say)
//! never stalls [`super::find`] or [`providers`] on another thread. It may be
//! called again by [`refresh_providers`], so it must be safe to run more than
//! once and must not modify the registry itself.

use std::collections::HashMap;
use std::path::PathBuf;
use std::sync::{Arc, LazyLock, Mutex, RwLock};
use std::time::Duration;

use super::{parse_builtin, Fingerprint};

/// Priority of the library embedded in this crate.
pub const PRIORITY_BUILTIN: i32 = 0;

/// Suggested priority for records fetched from a service.
pub const PRIORITY_CLOUD: i32 = 50;

/// Priority of a caller-registered provider. This is the
/// [`FingerprintProvider::priority`] default.
pub const PRIORITY_USER: i32 = 100;

/// A source of fingerprint records.
///
/// Implement this to supply records from anywhere: a file the application
/// ships, a licensed record service, a database, or a computed set. Register
/// the value with [`register_provider`]; every name it yields then resolves
/// through [`Profile::find`](crate::Profile::find).
pub trait FingerprintProvider: std::fmt::Debug + Send + Sync {
    /// Stable identifier, unique within the registry. Used in diagnostics.
    fn id(&self) -> &str;

    /// One sentence describing where the records come from.
    fn description(&self) -> &str {
        ""
    }

    /// Precedence against other providers. Higher wins a name clash.
    fn priority(&self) -> i32 {
        PRIORITY_USER
    }

    /// The records this provider supplies. Called at registration and by
    /// [`refresh_providers`].
    fn load(&self) -> Result<Vec<Fingerprint>, String>;
}

/// The library embedded in this crate.
///
/// Registered automatically under id `builtin` before any other provider.
#[derive(Debug, Default, Clone, Copy)]
pub struct BuiltinProvider;

impl BuiltinProvider {
    /// The id [`providers`] reports for the embedded library.
    pub const ID: &'static str = "builtin";
}

impl FingerprintProvider for BuiltinProvider {
    fn id(&self) -> &str {
        Self::ID
    }

    fn description(&self) -> &str {
        "fingerprints embedded in this crate, generated by tools/gen_fingerprints.py"
    }

    fn priority(&self) -> i32 {
        PRIORITY_BUILTIN
    }

    fn load(&self) -> Result<Vec<Fingerprint>, String> {
        parse_builtin()
    }
}

/// Records parsed from a JSON document in the library schema.
///
/// The document may hold one record or a list. Use [`JsonProvider::from_path`]
/// to read a file at load time, so a refresh picks up edits.
#[derive(Debug, Clone)]
pub struct JsonProvider {
    id: String,
    description: String,
    priority: i32,
    source: JsonSource,
}

#[derive(Debug, Clone)]
enum JsonSource {
    Text(String),
    File(PathBuf),
}

impl JsonProvider {
    /// Records from a JSON string that is already in memory.
    pub fn new(id: impl Into<String>, text: impl Into<String>) -> Self {
        Self {
            id: id.into(),
            description: String::new(),
            priority: PRIORITY_USER,
            source: JsonSource::Text(text.into()),
        }
    }

    /// Records from a JSON file, read again on every load.
    pub fn from_path(id: impl Into<String>, path: impl Into<PathBuf>) -> Self {
        Self {
            id: id.into(),
            description: String::new(),
            priority: PRIORITY_USER,
            source: JsonSource::File(path.into()),
        }
    }

    /// Set the description [`providers`] reports.
    pub fn with_description(mut self, description: impl Into<String>) -> Self {
        self.description = description.into();
        self
    }

    /// Set the precedence against other providers.
    pub fn with_priority(mut self, priority: i32) -> Self {
        self.priority = priority;
        self
    }
}

impl FingerprintProvider for JsonProvider {
    fn id(&self) -> &str {
        &self.id
    }

    fn description(&self) -> &str {
        &self.description
    }

    fn priority(&self) -> i32 {
        self.priority
    }

    fn load(&self) -> Result<Vec<Fingerprint>, String> {
        let text = match &self.source {
            JsonSource::Text(text) => text.clone(),
            JsonSource::File(path) => std::fs::read_to_string(path)
                .map_err(|error| format!("{}: {error}", path.display()))?,
        };
        super::parse_json(&text)
    }
}

/// Records from every `*.json` document in a directory, in file-name order.
#[derive(Debug, Clone)]
pub struct DirProvider {
    id: String,
    description: String,
    priority: i32,
    dir: PathBuf,
}

impl DirProvider {
    /// Read `<dir>/*.json` on every load.
    pub fn new(id: impl Into<String>, dir: impl Into<PathBuf>) -> Self {
        Self {
            id: id.into(),
            description: String::new(),
            priority: PRIORITY_USER,
            dir: dir.into(),
        }
    }

    /// Set the description [`providers`] reports.
    pub fn with_description(mut self, description: impl Into<String>) -> Self {
        self.description = description.into();
        self
    }

    /// Set the precedence against other providers.
    pub fn with_priority(mut self, priority: i32) -> Self {
        self.priority = priority;
        self
    }

    fn documents(&self) -> Result<Vec<PathBuf>, String> {
        let entries = std::fs::read_dir(&self.dir)
            .map_err(|error| format!("{}: {error}", self.dir.display()))?;
        let mut paths = Vec::new();
        for entry in entries {
            let entry = entry.map_err(|error| error.to_string())?;
            let path = entry.path();
            if path.is_file()
                && path
                    .extension()
                    .is_some_and(|extension| extension == "json")
            {
                paths.push(path);
            }
        }
        paths.sort();
        if paths.is_empty() {
            return Err(format!(
                "provider {}: no JSON documents in {}",
                self.id,
                self.dir.display()
            ));
        }
        Ok(paths)
    }
}

impl FingerprintProvider for DirProvider {
    fn id(&self) -> &str {
        &self.id
    }

    fn description(&self) -> &str {
        &self.description
    }

    fn priority(&self) -> i32 {
        self.priority
    }

    fn load(&self) -> Result<Vec<Fingerprint>, String> {
        let mut records = Vec::new();
        for path in self.documents()? {
            let text = std::fs::read_to_string(&path)
                .map_err(|error| format!("{}: {error}", path.display()))?;
            let mut parsed =
                super::parse_json(&text).map_err(|error| format!("{}: {error}", path.display()))?;
            records.append(&mut parsed);
        }
        Ok(records)
    }
}

/// Records produced by a closure.
///
