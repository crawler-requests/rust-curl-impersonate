/// Records fetched from a URL, with conditional revalidation.
///
/// This is the seam a cloud fingerprint service plugs into: point the provider
/// at a URL that serves the library schema and its records resolve like any
/// other provider's, with no crate release. The fetch runs through this crate's
/// own [`Client`](crate::Client), so the download itself impersonates a browser
/// profile, and the same client can attach a bearer token and custom headers.
///
/// The first `load` downloads the document and remembers the response's ETag. A
/// later [`refresh_providers`] round-trip re-fetches with `If-None-Match`; when
/// the server answers `304 Not Modified`, the cached records are handed back
/// unchanged, so an up-to-date library is never dropped by a refresh.
///
/// `load` is synchronous and runs on a private tokio runtime, so the provider
/// can be registered from a synchronous context. The fetch itself happens while
/// the provider registry is locked, as documented at the module level: keep the
/// URL fast and revalidating.
pub struct RemoteProvider {
    id: String,
    description: String,
    priority: i32,
    client: crate::Client,
    url: String,
    profile: crate::Profile,
    timeout: Duration,
    bearer: Option<String>,
    headers: Vec<(String, String)>,
    etag: Mutex<Option<String>>,
    cached: Mutex<Option<Vec<Fingerprint>>>,
}

impl RemoteProvider {
    /// Fetch records from `url`, impersonating Chrome 150 while downloading.
    pub fn new(id: impl Into<String>, url: impl Into<String>) -> Self {
        let profile = Self::default_profile();
        let timeout = Duration::from_secs(30);
        Self {
            id: id.into(),
            description: String::new(),
            priority: PRIORITY_CLOUD,
            client: Self::fetch_client(profile, timeout),
            url: url.into(),
            profile,
            timeout,
            bearer: None,
            headers: Vec::new(),
            etag: Mutex::new(None),
            cached: Mutex::new(None),
        }
    }

    fn default_profile() -> crate::Profile {
        crate::Profile::find("chrome150").expect("the chrome150 preset is always available")
    }

    fn fetch_client(profile: crate::Profile, timeout: Duration) -> crate::Client {
        crate::Client::builder(profile)
            .timeout(timeout)
            .build()
            .expect("the fetch profile builds a client")
    }

    /// Set the description [`providers`] reports.
    pub fn with_description(mut self, description: impl Into<String>) -> Self {
        self.description = description.into();
        self
    }

    /// Set the precedence against other providers.
    pub fn with_priority(mut self, priority: i32) -> Self {
        self.priority = priority;
        self
    }

    /// Send `Authorization: Bearer <token>` on every request.
    pub fn with_bearer_token(mut self, token: impl Into<String>) -> Self {
        self.bearer = Some(token.into());
        self
    }

    /// Add a header to every request, e.g. a subscription key.
    pub fn with_header(mut self, name: impl Into<String>, value: impl Into<String>) -> Self {
        self.headers.push((name.into(), value.into()));
        self
    }

    /// Acquire the document impersonating the given profile. Any resolvable
    /// preset or fingerprint works; this builder panics when `name` does not
    /// resolve.
    pub fn with_profile(mut self, name: &str) -> Self {
        let profile =
            crate::Profile::find(name).unwrap_or_else(|| panic!("unknown fetch profile {name}"));
        self.profile = profile;
        self.client = Self::fetch_client(profile, self.timeout);
        self
    }

    /// Bound every download, including the registration fetch.
    pub fn with_timeout(mut self, timeout: Duration) -> Self {
        self.timeout = timeout;
        self.client = Self::fetch_client(self.profile, timeout);
        self
    }

    async fn fetch(&self) -> Result<Vec<Fingerprint>, String> {
        let etag = self
            .etag
            .lock()
            .map_err(|_| "etag cache poisoned".to_string())?
            .clone();
        let mut request = self.client.get(self.url.as_str());
        if let Some(etag) = etag {
            request = request.header("If-None-Match", etag);
        }
        if let Some(token) = &self.bearer {
            request = request.header("Authorization", format!("Bearer {token}"));
        }
        for (name, value) in &self.headers {
            request = request.header(name, value);
        }
        let response = request.send().await.map_err(|error| error.to_string())?;
        let status = response.status().as_u16();
        if status == 304 {
            return self
                .cached
                .lock()
                .map_err(|_| "cache poisoned".to_string())?
                .clone()
                .ok_or_else(|| "server answered 304 without a cached document".to_string());
        }
        if status != 200 {
            return Err(format!("server returned HTTP {status} for {}", self.url));
        }
        let next_etag = response
            .headers()
            .get("etag")
            .and_then(|value| value.to_str().ok())
            .map(str::to_string);
        let records =
            super::parse_json(&response.text().await.map_err(|error| error.to_string())?)?;
        if let Some(etag) = next_etag {
            *self
                .etag
                .lock()
                .map_err(|_| "etag cache poisoned".to_string())? = Some(etag);
        }
        *self
            .cached
            .lock()
            .map_err(|_| "cache poisoned".to_string())? = Some(records.clone());
        Ok(records)
    }
}

impl std::fmt::Debug for RemoteProvider {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("RemoteProvider")
            .field("id", &self.id)
            .field("description", &self.description)
            .field("priority", &self.priority)
            .field("url", &self.url)
            .field("profile", &self.profile.name())
            .field("bearer", &self.bearer.as_ref().map(|_| "***"))
            .field("headers", &self.headers)
            .finish_non_exhaustive()
    }
}

impl FingerprintProvider for RemoteProvider {
    fn id(&self) -> &str {
        &self.id
    }

    fn description(&self) -> &str {
        &self.description
    }

    fn priority(&self) -> i32 {
        self.priority
    }

    fn load(&self) -> Result<Vec<Fingerprint>, String> {
        REMOTE_RUNTIME
            .block_on(self.fetch())
            .map_err(|error| format!("provider {}: {error}", self.id))
    }
}

/// Private runtime shared by every [`RemoteProvider`].
static REMOTE_RUNTIME: LazyLock<tokio::runtime::Runtime> = LazyLock::new(|| {
    tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .expect("a tokio runtime for remote fingerprint providers")
});

/// One provider as [`providers`] reports it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProviderInfo {
    /// The provider's [`FingerprintProvider::id`].
    pub id: String,
    /// The provider's [`FingerprintProvider::description`], or an empty string.
    pub description: String,
    /// The precedence the provider was registered with.
    pub priority: i32,
    /// How many records the provider currently supplies.
    pub records: usize,
    /// Names this provider takes over from a lower-priority provider.
    pub overrides: Vec<String>,
}

/// The merged view every lookup reads.
pub(crate) struct Snapshot {
    /// Winning record per name, in first-provider order.
    pub(crate) records: Vec<&'static Fingerprint>,
    /// The same records keyed by name.
    pub(crate) index: HashMap<&'static str, &'static Fingerprint>,
}

struct Registered {
    provider: Arc<dyn FingerprintProvider>,
    priority: i32,
    /// Registration sequence, used to break priority ties.
    order: usize,
    records: &'static [Fingerprint],
}

struct State {
    providers: Vec<Registered>,
    builtin_loaded: bool,
    next_order: usize,
    snapshot: Option<&'static Snapshot>,
}

static STATE: LazyLock<RwLock<State>> = LazyLock::new(|| {
    RwLock::new(State {
        providers: Vec::new(),
        builtin_loaded: false,
        next_order: 0,
        snapshot: None,
    })
});

fn state() -> std::sync::RwLockReadGuard<'static, State> {
    STATE.read().expect("fingerprint provider registry")
}

fn state_mut() -> std::sync::RwLockWriteGuard<'static, State> {
    STATE.write().expect("fingerprint provider registry")
}

/// The merged records, loading the embedded library on first use.
pub(crate) fn snapshot() -> &'static Snapshot {
    {
        let state = state();
        if let Some(snapshot) = state.snapshot {
            return snapshot;
        }
    }
    let mut state = state_mut();
    if state.snapshot.is_none() {
        load_builtin(&mut state).expect("the embedded fingerprint JSON parses");
    }
    state.snapshot.expect("the snapshot was just built")
}

fn load_builtin(state: &mut State) -> Result<(), String> {
    if state.builtin_loaded {
        return Ok(());
    }
    let records: &'static [Fingerprint] = Box::leak(BuiltinProvider.load()?.into_boxed_slice());
    state.providers.push(Registered {
        provider: Arc::new(BuiltinProvider),
        priority: PRIORITY_BUILTIN,
        order: state.next_order,
        records,
    });
    state.next_order += 1;
    state.builtin_loaded = true;
    rebuild(state);
    Ok(())
}

/// Recompute the merged view. A later provider replaces a name in place, so
/// the listing keeps the position the name first appeared at.
fn rebuild(state: &mut State) {
    let mut records: Vec<&'static Fingerprint> = Vec::new();
    let mut index: HashMap<&'static str, &'static Fingerprint> = HashMap::new();
    let mut positions: HashMap<&'static str, usize> = HashMap::new();
    let mut order: Vec<usize> = (0..state.providers.len()).collect();
    order.sort_by_key(|&at| (state.providers[at].priority, state.providers[at].order));
    for at in order {
        for record in state.providers[at].records {
            let name = record.name.as_str();
            match positions.get(name) {
                Some(&position) => {
                    records[position] = record;
                    index.insert(name, record);
                }
                None => {
                    positions.insert(name, records.len());
                    index.insert(name, record);
                    records.push(record);
                }
            }
        }
    }
    state.snapshot = Some(Box::leak(Box::new(Snapshot { records, index })));
}

/// Register `provider` with the priority it reports.
///
/// Fails when its id is empty, reserved, or already registered, when two of its
/// records share a name, when an empty name appears, or when a record extends a
/// profile no provider and no target supplies.
pub fn register_provider<P>(provider: P) -> Result<(), String>
where
    P: FingerprintProvider + 'static,
{
    let priority = provider.priority();
    register_boxed(Arc::new(provider), priority)
}

/// Register `provider`, overriding the priority it reports.
///
/// A higher priority wins a name clash; equal priorities go to the provider
/// registered later.
pub fn register_provider_with_priority<P>(provider: P, priority: i32) -> Result<(), String>
where
    P: FingerprintProvider + 'static,
{
    register_boxed(Arc::new(provider), priority)
}

fn register_boxed(provider: Arc<dyn FingerprintProvider>, priority: i32) -> Result<(), String> {
    let id = provider.id().trim().to_string();
    if id.is_empty() {
        return Err("provider id is empty".to_string());
    }
    if id == BuiltinProvider::ID {
        return Err(format!("provider id {id} is reserved"));
    }
    // `load` runs outside the write lock so a slow provider (a network fetch,
    // say) never stalls lookups on another thread.
    let records = provider.load()?;
    let mut seen = HashMap::new();
    for record in &records {
        if record.name.is_empty() {
            return Err(format!("provider {id} has a record with an empty name"));
        }
        if seen.insert(record.name.clone(), ()).is_some() {
            return Err(format!(
                "provider {id} has two records named {}",
                record.name
            ));
        }
        // A non-alias record must build its wire options now, so a malformed
        // document is rejected at registration instead of on first use. An
        // alias is checked by `check_bases` after it is in the snapshot.
        if record.extends.is_none() {
            record.emulation()?;
            if record.http3.is_some() {
                record.http3_profile()?;
            }
        }
    }
    {
        let mut state = state_mut();
        load_builtin(&mut state)?;
        if state
            .providers
            .iter()
            .any(|entry| entry.provider.id() == id)
        {
            return Err(format!("provider {id} is already registered"));
        }
        let records: &'static [Fingerprint] = Box::leak(records.into_boxed_slice());
        let order = state.next_order;
        state.next_order += 1;
        state.providers.push(Registered {
            provider,
            priority,
            order,
            records,
        });
        rebuild(&mut state);
    }
    // A record may extend one that only becomes resolvable once the provider is
    // in the snapshot, so check the bases afterwards. `Profile::find` takes the
    // registry read lock and must run with the write lock released.
    if let Err(error) = check_bases(&id) {
        let _ = unregister_provider(&id);
        return Err(error);
    }
    Ok(())
}

/// Every provider's records must resolve their `extends` target.
fn check_bases(id: &str) -> Result<(), String> {
    let bases: Vec<(String, String)> = {
        let state = state();
        let Some(entry) = state
            .providers
            .iter()
            .find(|entry| entry.provider.id() == id)
        else {
            return Ok(());
        };
        entry
            .records
            .iter()
            .filter_map(|record| {
                record
                    .extends
                    .as_ref()
                    .map(|base| (record.name.clone(), base.clone()))
            })
            .collect()
    };
    for (name, base) in bases {
        if name == base {
            return Err(format!("{name} cannot extend itself"));
        }
        if crate::profile::Profile::find(&base).is_none() {
            return Err(format!("{name} extends unknown profile {base}"));
        }
    }
    Ok(())
}

/// Remove a provider and rebuild the merged view.
///
/// The embedded library cannot be removed. Names the provider supplied stop
/// resolving unless another provider or a target still supplies them.
pub fn unregister_provider(id: &str) -> Result<(), String> {
    if id == BuiltinProvider::ID {
        return Err("the embedded library cannot be unregistered".to_string());
    }
    let mut state = state_mut();
    let before = state.providers.len();
    state.providers.retain(|entry| entry.provider.id() != id);
    if before == state.providers.len() {
        return Err(format!("no provider named {id}"));
    }
    rebuild(&mut state);
    Ok(())
}

/// Reload every provider except the embedded library.
///
/// Records that changed are replaced; records that did not are kept as they
/// are. Failures are collected and returned after the providers that did load
/// are applied. Each `load` runs without the registry lock, so a slow provider
/// does not stall lookups; a provider unregistered while it reloads is skipped
/// when the results are applied.
pub fn refresh_providers() -> Result<(), String> {
    // Make sure the embedded library is registered before the providers are
    // collected.
    let _ = snapshot();
    let pending: Vec<(String, Arc<dyn FingerprintProvider>)> = {
        let state = state();
        state
            .providers
            .iter()
            .filter(|entry| entry.provider.id() != BuiltinProvider::ID)
            .map(|entry| (entry.provider.id().to_string(), Arc::clone(&entry.provider)))
            .collect()
    };
    let mut loaded = Vec::with_capacity(pending.len());
    for (id, provider) in pending {
        loaded.push((id, provider.load()));
    }
    let mut failures = Vec::new();
    {
        let mut state = state_mut();
        for (id, result) in loaded {
            let Ok(records) = result else {
                failures.push(format!("{id}: {}", result.unwrap_err()));
                continue;
            };
            let Some(entry) = state
                .providers
                .iter_mut()
                .find(|entry| entry.provider.id() == id)
            else {
                // The provider was unregistered while its load was running.
                continue;
            };
            let changed = match (
                serde_json::to_string(&entry.records),
                serde_json::to_string(&records),
            ) {
                (Ok(current), Ok(next)) => current != next,
                _ => true,
            };
            if changed {
                entry.records = Box::leak(records.into_boxed_slice());
            }
        }
        rebuild(&mut state);
    }
    if failures.is_empty() {
        Ok(())
    } else {
        Err(failures.join("; "))
    }
}

/// Every registered provider, in registration order.
///
/// The embedded library is always first. `overrides` lists the names a provider
/// takes over from a lower-priority provider.
pub fn providers() -> Vec<ProviderInfo> {
    // Build the snapshot first so the embedded library is registered before the
    // read lock is taken.
    let _ = snapshot();
    let state = state();
    let mut infos: Vec<ProviderInfo> = state
        .providers
        .iter()
        .map(|entry| ProviderInfo {
            id: entry.provider.id().to_string(),
            description: entry.provider.description().to_string(),
            priority: entry.priority,
            records: entry.records.len(),
            overrides: Vec::new(),
        })
        .collect();
    let mut order: Vec<usize> = (0..state.providers.len()).collect();
    order.sort_by_key(|&at| (state.providers[at].priority, state.providers[at].order));
    let mut owner: HashMap<&str, usize> = HashMap::new();
    for at in order {
        for record in state.providers[at].records {
            if let Some(previous) = owner.insert(record.name.as_str(), at) {
                if previous != at {
                    infos[at].overrides.push(record.name.clone());
                }
            }
        }
    }
    infos
}

/// The provider whose records won `name`, or `None`.
pub fn provider_of(name: &str) -> Option<ProviderInfo> {
    let _ = snapshot();
    let state = state();
    // Highest precedence first: the first provider that has the name is the one
    // the merged view took it from.
    let mut order: Vec<usize> = (0..state.providers.len()).collect();
    order.sort_by_key(|&at| {
        std::cmp::Reverse((state.providers[at].priority, state.providers[at].order))
    });
    for at in order {
        if state.providers[at]
            .records
            .iter()
            .any(|record| record.name == name)
        {
            let entry = &state.providers[at];
            return Some(ProviderInfo {
                id: entry.provider.id().to_string(),
                description: entry.provider.description().to_string(),
                priority: entry.priority,
                records: entry.records.len(),
                overrides: Vec::new(),
            });
        }
    }
    None
}
